export function searchMice(query) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return MICE.slice(0, 40);
  const res = MICE.filter(m => (m.brand + ' ' + m.model).toLowerCase().includes(q));
  return res.length > 60 ? res.slice(0, 60) : res;
}
