-- COMO USAR (1 minuto):
--   1. Cria um projeto grátis em https://supabase.com
--   2. No painel: SQL Editor -> New query -> cola este ficheiro -> Run
--   3. Project Settings -> API -> copia os dois valores para
--      o ficheiro server/.env:
--         SUPABASE_URL=...        ("Project URL")
--         SUPABASE_SERVICE_KEY=... ("service_role" key)
--   4. Reinicia o servidor (INICIAR.bat)
--
-- Nota: os clips ficam ligados a cada conta por "user_id"
--       (fase seguinte — este ficheiro prepara já a tabela).
-- ============================================================

create table if not exists public.users (
  id             bigint generated by default as identity primary key,
  username       text not null,                  -- nome visível
  username_lower text not null unique,           -- cópia em minúsculas (pesquisa)
  password_hash  text not null,                  -- hash da palavra-passe (bcrypt)
  email          text unique,                    -- email da conta (recuperação de pass)
  is_admin       boolean not null default false, -- conta com acesso ao painel admin
  created_at     timestamptz not null default now()
);

-- Se a tabela já foi criada antes desta versão, corre também:
alter table public.users
  add column if not exists is_admin boolean not null default false;
alter table public.users
  add column if not exists email text unique;

-- Segurança: ninguém lê nem escreve as contas diretamente do
-- browser; só o servidor (chave service_role) acede.
alter table public.users enable row level security;

-- ============================================================
-- Definicoes do site (tema, etc.) — escolhidas no painel admin.
-- O servidor e o unico que le e escreve aqui.
-- ============================================================
create table if not exists public.site_settings (
  k          text primary key,                -- chave (ex.: 'theme')
  v          text not null,                   -- valor (ex.: 'normal')
  updated_at timestamptz not null default now()
);

alter table public.site_settings enable row level security;
