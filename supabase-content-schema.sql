--  Ronda nova: notificações, push, coleções e likes de comentários
-- ============================================================

-- Likes em comentários (clips e publicações)
create table if not exists public.comment_likes (
  comment_id integer   not null,
  kind       text      not null default 'clip',  -- 'clip' | 'post'
  user_id    bigint    not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (comment_id, kind, user_id)
);

-- Notificações (dentro do site + origem do push)
create table if not exists public.notifications (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references public.users(id) on delete cascade,
  actor_id   bigint references public.users(id) on delete set null,
  type       text   not null,        -- 'comment' | 'reply' | 'like' | 'save' | 'badge' | 'system'
  entity     text   not null,        -- 'clip' | 'post' | 'user'
  entity_id  bigint,
  title      text   not null,
  body       text   not null default '',
  link       text,
  read_at    timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists idx_notifications_user on public.notifications (user_id, created_at desc);

-- Subscrições Web Push (um registo por dispositivo)
create table if not exists public.push_subs (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references public.users(id) on delete cascade,
  endpoint   text   not null unique,
  p256dh     text   not null,
  auth       text   not null,
  user_agent text,
  created_at timestamptz not null default now()
);

-- Coleções de clips (pastas próprias sobre os guardados)
create table if not exists public.clip_collections (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references public.users(id) on delete cascade,
  name       text   not null,
  created_at timestamptz not null default now(),
  unique (user_id, name)
);

create table if not exists public.clip_collection_items (
  collection_id bigint  not null references public.clip_collections(id) on delete cascade,
  clip_id       integer not null references public.clips(id) on delete cascade,
  created_at    timestamptz not null default now(),
  primary key (collection_id, clip_id)
);
