-- ---------- visitantes / estatísticas de tráfego ----------
create table if not exists public.visitors (
  id          integer generated by default as identity primary key,
  ip          text,
  user_agent  text,
  visited_at  timestamptz not null default now(),
  is_online   integer not null default 1
);
create index if not exists idx_visitors_ip   on public.visitors (ip);
create index if not exists idx_visitors_time on public.visitors (visited_at desc);

-- ---------- anúncios / publicações ----------
create table if not exists public.posts (
  id         integer generated by default as identity primary key,
  title      text not null,
  content    text not null,
  image_url  text,
  likes      integer not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists idx_posts_created on public.posts (created_at desc);

create table if not exists public.post_likes (
  id       integer generated by default as identity primary key,
  post_id  integer references public.posts(id) on delete cascade,
  ip       text,
  liked_at timestamptz not null default now()
);
create index if not exists idx_post_likes_post on public.post_likes (post_id, ip);

create table if not exists public.post_comments (
  id         integer generated by default as identity primary key,
  post_id    integer references public.posts(id) on delete cascade,
  author     text,
  content    text,
  created_at timestamptz not null default now()
);
create index if not exists idx_post_comments_post on public.post_comments (post_id, created_at);

-- ---------- sessões (reserva) ----------
create table if not exists public.admin_sessions (
  id         integer generated by default as identity primary key,
  token      text,
  created_at timestamptz not null default now()
);

-- ---------- distinções / joias do perfil ----------
create table if not exists public.user_badges (
  user_id    bigint not null references public.users(id) on delete cascade,
  badge      text   not null,
  granted_by bigint,
  granted_at timestamptz not null default now(),
  primary key (user_id, badge)
);

-- ---------- dados extras do perfil ----------
create table if not exists public.user_profiles (
  user_id    bigint primary key references public.users(id) on delete cascade,
  avatar_url text,
  game_nick  text,
  updated_at timestamptz not null default now()
);

-- ---------- recuperação de palavra-passe ----------
create table if not exists public.pass_recovery (
  id         integer generated by default as identity primary key,
  user_id    bigint not null,
  username   text   not null unique,
  email      text,
  status     text   not null default 'pending',   -- pending | sent | used | locked
  token      text,
  expires_at timestamptz,
  code       text,
  attempts   integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_pass_recovery_token on public.pass_recovery (token);

-- ---------- clips publicados ----------
create table if not exists public.clips (
  id         integer generated by default as identity primary key,
  user_id    bigint not null references public.users(id) on delete cascade,
  title      text   not null,
  file       text   not null,
  start_sec  real   not null default 0,
  end_sec    real,
  visibility text   not null default 'public',
  likes      integer not null default 0,
  saves      integer not null default 0,
  downloads  integer not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists idx_clips_created    on public.clips (created_at desc);
create index if not exists idx_clips_user       on public.clips (user_id);
create index if not exists idx_clips_visibility on public.clips (visibility);

create table if not exists public.clip_likes (
  clip_id    integer not null references public.clips(id) on delete cascade,
  user_id    bigint  not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (clip_id, user_id)
);

create table if not exists public.clip_saves (
  clip_id    integer not null references public.clips(id) on delete cascade,
  user_id    bigint  not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (clip_id, user_id)
);

create table if not exists public.clip_comments (
  id         integer generated by default as identity primary key,
  clip_id    integer not null references public.clips(id) on delete cascade,
  user_id    bigint  not null references public.users(id) on delete cascade,
  parent_id  integer references public.clip_comments(id) on delete cascade,
  content    text    not null,
  created_at timestamptz not null default now()
);
create index if not exists idx_clip_comments_clip on public.clip_comments (clip_id, created_at);

